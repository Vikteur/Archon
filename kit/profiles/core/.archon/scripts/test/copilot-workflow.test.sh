#!/usr/bin/env bash
# Tests for .archon/scripts/copilot-workflow.js, the generator of build-feature-copilot.yaml: the committed file is in sync,
# it keeps build-feature's nodes and bash/script fields (bar the audit adapter prefix), none of the Claude-only strings
# remain, a rewrite whose anchor is gone fails with exit 2 and writes nothing, and the config holds the Copilot aliases.
# Usage: bash .archon/scripts/test/copilot-workflow.test.sh   (exit 0 = all pass)
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
repo="$(cd "$here/../.." && pwd)"
gen="$here/copilot-workflow.js"
src="$repo/.archon/workflows/build-feature.yaml"
out_wf="$repo/.archon/workflows/build-feature-copilot.yaml"
pass=0; fail=0; out=""
root="$(mktemp -d)"
trap 'rm -rf "$root"' EXIT
check() { if [ "$2" -eq 0 ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL: $1"; echo "$out" | sed 's/^/    /'; fi; }

# Every node as `<id>\t<bash field as JSON>`, loop nodes included, in file order
nodes() { yq -o=json '.' "$1" | node -e '
  const wf = JSON.parse(require("fs").readFileSync(0, "utf8"));
  const walk = ns => { for (const n of ns || []) {
    console.log(n.id + "\t" + JSON.stringify(n.bash || "") + "\t" + JSON.stringify(n.script || ""));
    walk(n.loop_group && n.loop_group.nodes); walk(n.loop && n.loop.nodes); walk(n.nodes);
  } };
  walk(wf.nodes);'; }
prefix='node .archon/scripts/copilot-audit.js "$WORKFLOW_ID" && '

# 1. In sync.
out=$(node "$gen" --check 2>&1); check "1 --check passes on the committed file" $?
head -1 "$out_wf" | grep -q '^# GENERATED by .archon/scripts/copilot-workflow.js from build-feature.yaml'; check "1 header line" $?

# 2. Same node ids, in the same order.
out=$(diff <(nodes "$src" | cut -f1) <(nodes "$out_wf" | cut -f1) 2>&1); check "2 node ids equal build-feature's" $?

# 3. bash and script fields equal the original once the audit prefix is stripped; exactly three nodes carry it.
nodes "$out_wf" | sed "s#node .archon/scripts/copilot-audit.js \\\\\"\$WORKFLOW_ID\\\\\" \\&\\& ##" > "$root/stripped"
out=$(diff <(nodes "$src") "$root/stripped" 2>&1); check "3 bash/script fields equal the original bar the prefix" $?
n=$(nodes "$out_wf" | grep -c 'copilot-audit.js'); out="$n nodes carry the prefix"
check "3 exactly three nodes carry the audit prefix" $([ "$n" -eq 3 ]; echo $?)
for id in tests-check step-check skill-check; do
  nodes "$out_wf" | grep -P "^$id\t" | grep -q 'copilot-audit.js'; check "3 $id runs the audit adapter first" $?
done

# 4. Nothing Claude-only is left.
for s in '"@build"' '"@analyse"' '"@scout"' 'Claude Code' 'Agent tool' 'noreply@anthropic.com' 'allowed_tools'; do
  out=$(grep -nF -- "$s" "$out_wf"); check "4 no '$s' left" $([ -z "$out" ]; echo $?)
done
grep -qF 'Co-Authored-By: GitHub Copilot <noreply@github.com>' "$out_wf"; check "4 the Copilot trailer is in" $?
grep -qF 'Read .github/agents/github-agent.agent.md and follow it yourself' "$out_wf"; check "4 the github-agent node reads its own file" $?
[ "$(yq '.name' "$out_wf")" = build-feature-copilot ]; check "4 workflow name" $?
yq '.description' "$out_wf" | head -1 | grep -q '^Copilot variant of build-feature, generated. Use only when the owner asks for GitHub Copilot.'; check "4 description" $?
[ "$(grep -c 'model: "@[a-z]*-copilot"' "$out_wf")" -eq "$(grep -cE 'model: "@(scout|build|analyse)"' "$src")" ]; check "4 every aliased node is on a -copilot alias" $?
[ "$(grep -c 'denied_tools:' "$out_wf")" -eq "$(grep -c 'denied_tools:' "$src")" ]; check "4 denied_tools kept on every node" $?

# 5. A rewrite whose anchor is gone: exit 2, nothing written. A throwaway root with a build-feature.yaml that lacks one.
mkdir -p "$root/t/.archon/workflows"
sed 's/with the Skill tool/with a tool/' "$src" > "$root/t/.archon/workflows/build-feature.yaml"
out=$(COPILOT_WORKFLOW_ROOT="$root/t" node "$gen" 2>&1); rc=$?
check "5 an anchor gone: exit 2" $([ "$rc" -eq 2 ]; echo $?)
check "5 nothing written" $([ ! -e "$root/t/.archon/workflows/build-feature-copilot.yaml" ]; echo $?)
echo "$out" | grep -q 'skill tool'; check "5 names the rewrite" $?
# A global replacement tolerates a different count (a new node on @build, one more Skill-tool line); a single anchor does not.
{ cat "$src"; printf '\n# extra: model: "@build" with the Skill tool\n'; } > "$root/t/.archon/workflows/build-feature.yaml"
out=$(COPILOT_WORKFLOW_ROOT="$root/t" node "$gen" 2>&1); check "5 one more occurrence of a global replacement still generates" $?
{ cat "$src"; printf '\n# 🤖 Generated with [Claude Code](https://claude.com/claude-code)\n'; } > "$root/t/.archon/workflows/build-feature.yaml"
out=$(COPILOT_WORKFLOW_ROOT="$root/t" node "$gen" 2>&1); rc=$?
check "5 a second occurrence of a single anchor: exit 2" $([ "$rc" -eq 2 ]; echo $?)
echo "$out" | grep -q 'pr footer'; check "5 names the single anchor" $?
# ...and the clean copy generates the same file as the committed one.
cp "$src" "$root/t/.archon/workflows/build-feature.yaml"
out=$(COPILOT_WORKFLOW_ROOT="$root/t" node "$gen" 2>&1); check "5 a clean copy generates" $?
out=$(cmp "$root/t/.archon/workflows/build-feature-copilot.yaml" "$out_wf" 2>&1); check "5 same bytes as the committed file" $?
# --check on a drifted file: exit 1.
echo '# drift' >> "$root/t/.archon/workflows/build-feature-copilot.yaml"
out=$(COPILOT_WORKFLOW_ROOT="$root/t" node "$gen" --check 2>&1); rc=$?
check "5 --check on a drifted file: exit 1" $([ "$rc" -eq 1 ]; echo $?)

# 6. Config: three Copilot aliases, the Claude ones unchanged.
cfg="$repo/.archon/config.yaml"
for a in scout build analyse; do
  [ "$(yq ".aliases.\"@$a-copilot\".provider" "$cfg")" = copilot ]; check "6 @$a-copilot provider copilot" $?
  [ -n "$(yq ".aliases.\"@$a-copilot\".model" "$cfg" | grep -v '^null$')" ]; check "6 @$a-copilot has a model" $?
  [ "$(yq ".aliases.\"@$a\".provider" "$cfg")" = claude ]; check "6 @$a still claude" $?
done
[ "$(yq '.aliases."@build".model' "$cfg")" = claude-sonnet-5-5 ] && [ "$(yq '.aliases."@analyse".model' "$cfg")" = claude-opus-5-5 ] \
  && [ "$(yq '.aliases."@scout".model' "$cfg")" = claude-haiku-5-5 ]; check "6 Claude model ids unchanged" $?

echo "copilot-workflow: $pass passed, $fail failed"
[ "$fail" -eq 0 ]

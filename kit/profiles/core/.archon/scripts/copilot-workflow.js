// Generator (P2: a script, not a model) of .archon/workflows/build-feature-copilot.yaml from build-feature.yaml.
//   node copilot-workflow.js           write the Copilot variant
//   node copilot-workflow.js --check   exit 1 when the committed file differs from what would be generated
// Text-based, exact-string rewrites, each with the count it must match in build-feature.yaml: an exact number for a
// single anchor (name, PR footer, github-agent prompt, explore allowed_tools, the audit prefixes), '+' (at least one) for
// a global replacement that applies wherever it occurs (model aliases, `with the Skill tool`, trailers). A count that does
// not fit means build-feature.yaml moved under the rewrite, so nothing is written and the exit code is 2 (fix the list here).
// Node ids and every bash:/script: field stay as they are, except the audit adapter prefix on three gate nodes.
// Narrowings the Copilot variant records (docs/memory.md, 2026-11-19): the explore node's allowed_tools is dropped (Archon
// passes it to Copilot as availableTools, and Claude's tool names match none of Copilot's: P8); `mcp:` keys stay (Copilot supports them); denied_tools stay verbatim
// but do not bind on Copilot, the commit-msg hook and the tdd-check node are the gates there (P6).
const fs = require('fs');
const path = require('path');

const ROOT = process.env.COPILOT_WORKFLOW_ROOT || path.resolve(__dirname, '..', '..');
const SRC = path.join(ROOT, '.archon', 'workflows', 'build-feature.yaml');
const OUT = path.join(ROOT, '.archon', 'workflows', 'build-feature-copilot.yaml');
const HEADER = '# GENERATED by .archon/scripts/copilot-workflow.js from build-feature.yaml — do not edit\n';
const AUDIT = 'node .archon/scripts/copilot-audit.js "$WORKFLOW_ID" && ';
const TRAILER = 'Co-Authored-By: GitHub Copilot <noreply@github.com>';

// [label, from, to, expected count: a number, or '+' for at least one]
const RULES = [
  ['name', 'name: build-feature\ndescription: |\n  Use when:',
    'name: build-feature-copilot\ndescription: |\n  Copilot variant of build-feature, generated. Use only when the owner asks for GitHub Copilot.\n  Use when:', 1],
  ['scout model', 'model: "@scout"', 'model: "@scout-copilot"', '+'],
  ['build model', 'model: "@build"', 'model: "@build-copilot"', '+'],
  ['analyse model', 'model: "@analyse"', 'model: "@analyse-copilot"', '+'],
  ['skill tool', 'with the Skill tool', 'with the skill tool', '+'],
  ['sonnet trailer', 'Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>', TRAILER, '+'],
  ['opus trailer', 'Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>', TRAILER, '+'],
  ['pr footer', '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    '🤖 Generated with GitHub Copilot through Archon (build-feature-copilot)', 1],
  ['github agent',
    'Use the Agent tool with the `github-agent` subagent for this job; when subagents\n            are not available, read .claude/agents/github-agent.md and follow it yourself, its allowlist included.\n',
    'Read .claude/agents/github-agent.md and follow it yourself, its allowlist included; this node has no subagents.\n', 1],
  ['explore allowed_tools',
    '    allowed_tools: [Read, Grep, Glob, Write, "Bash(git log *)", "Bash(git ls-files *)", "mcp__portal-api__*",\n      "mcp__codegraph__*"]\n', '', 1],
  ['tests-check audit', 'node .archon/scripts/step-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID" test',
    `${AUDIT}node .archon/scripts/step-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID" test`, 1],
  ['step-check audit', 'node .archon/scripts/step-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID" build',
    `${AUDIT}node .archon/scripts/step-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID" build`, 1],
  ['skill-check audit', 'node .archon/scripts/skill-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID"\n',
    `${AUDIT}node .archon/scripts/skill-check.js "$ARTIFACTS_DIR" "$WORKFLOW_ID"\n`, 1],
];

const count = (s, needle) => s.split(needle).length - 1;

// The generated text; throws { rule, found, expected } on a count mismatch
function generate(source) {
  let text = source;
  for (const [label, from, to, expected] of RULES) {
    const found = count(text, from);
    if (expected === '+' ? found < 1 : found !== expected) throw Object.assign(new Error(`rewrite "${label}": found ${found}, expected ${expected === '+' ? 'at least 1' : expected}`), { code: 2 });
    text = text.split(from).join(to);
  }
  return HEADER + text;
}

if (require.main === module) {
  const check = process.argv[2] === '--check';
  let out;
  try { out = generate(fs.readFileSync(SRC, 'utf8')); } catch (e) {
    console.error(`copilot-workflow: ${e.message}${e.code === 2 ? ' (build-feature.yaml moved under the rewrite list)' : ''}`);
    process.exit(e.code === 2 ? 2 : 1);
  }
  if (check) {
    let have = null;
    try { have = fs.readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== out) { console.error('copilot-workflow: build-feature-copilot.yaml is out of date; run node .archon/scripts/copilot-workflow.js'); process.exit(1); }
    console.log('copilot-workflow: build-feature-copilot.yaml is in sync');
  } else {
    fs.writeFileSync(OUT, out);
    console.log(`copilot-workflow: wrote ${path.relative(ROOT, OUT)} (${RULES.length} rewrite rules)`);
  }
}

module.exports = { generate, RULES };

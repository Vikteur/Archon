#!/usr/bin/env bun
/**
 * Writes packages/cli/src/bundled-kit.ts from the committed Copilot kit (kit/manifest.json, kit/kit.defaults.yaml and
 * kit/profiles/**), so `archon kit add` works from the compiled binary without the repo. kit/SPEC.md is the contract.
 *
 * Usage:
 *   bun run scripts/generate-bundled-kit.ts                         # write
 *   bun run scripts/generate-bundled-kit.ts --check                 # verify (exit 2 if stale)
 *   bun run scripts/generate-bundled-kit.ts --kit <dir> --out <ts>  # another kit or output file (tests)
 *
 * Exit codes:
 *   0  file generated (and unchanged, if --check)
 *   1  unexpected error (a manifest file missing or its sha256 differs)
 *   2  --check was passed and the file would change
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const REPO_ROOT = resolve(import.meta.dir, '..');

interface ManifestFile {
  path: string;
  profile: string;
  sha256: string;
}

export function renderBundledKit(kitDir: string): string {
  const manifestText = readFileSync(join(kitDir, 'manifest.json'), 'utf8');
  const manifest = JSON.parse(manifestText) as { files: ManifestFile[] };
  const defaults = readFileSync(join(kitDir, 'kit.defaults.yaml'), 'utf8');
  const files: string[] = [];
  for (const f of manifest.files) {
    const key = `${f.profile}/${f.path}`;
    const full = join(kitDir, 'profiles', key);
    if (!existsSync(full))
      throw new Error(`${key}: in manifest.json but not in profiles/ (run kit:sync)`);
    const content = readFileSync(full, 'utf8');
    if (createHash('sha256').update(content).digest('hex') !== f.sha256)
      throw new Error(`${key}: sha256 differs from manifest.json (run kit:sync)`);
    files.push(`    ${JSON.stringify(key)}: ${JSON.stringify(content)},`);
  }
  return [
    '// AUTO-GENERATED by scripts/generate-bundled-kit.ts — DO NOT EDIT.',
    '// Source: kit/manifest.json, kit/kit.defaults.yaml and kit/profiles/** (contract: kit/SPEC.md).',
    '// Regenerate with `bun run kit:bundle`; `bun run check:bundled-kit` fails when it is stale.',
    '',
    'export interface KitManifestFile {',
    '  path: string;',
    '  profile: string;',
    '  mode: string;',
    '  template: boolean;',
    '  origin: string | null;',
    '  kind: string;',
    '  sha256: string;',
    '  createOnly?: boolean;',
    '}',
    '',
    'export interface KitManifest {',
    '  version: 1;',
    '  source: { name: string; commit: string };',
    '  profiles: Record<string, { requires: string[]; description: string; project?: boolean }>;',
    '  exclusive: string[][];',
    '  files: KitManifestFile[];',
    '  aliases: Record<string, { provider: string; model: string }>;',
    '  postInstall: { profile: string; run: string; optional: boolean }[];',
    '}',
    '',
    'export const BUNDLED_KIT: {',
    '  manifest: KitManifest;',
    '  defaults: string /* kit.defaults.yaml text */;',
    '  files: Record<string /* `${profile}/${path}` */, string /* utf8 */>;',
    '} = {',
    `  manifest: ${manifestText.trimEnd().split('\n').join('\n  ')},`,
    `  defaults: ${JSON.stringify(defaults)},`,
    '  files: {',
    ...files,
    '  },',
    '};',
    '',
  ].join('\n');
}

function main(argv: string[]): number {
  let kitDir = join(REPO_ROOT, 'kit');
  let out = join(REPO_ROOT, 'packages/cli/src/bundled-kit.ts');
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') check = true;
    else if (a === '--kit') kitDir = resolve(argv[++i] ?? '');
    else if (a === '--out') out = resolve(argv[++i] ?? '');
    else {
      console.error(`unknown argument ${a}`);
      return 1;
    }
  }
  let text: string;
  try {
    text = renderBundledKit(kitDir);
  } catch (e) {
    console.error(`generate-bundled-kit: ${(e as Error).message}`);
    return 1;
  }
  const rel = relative(REPO_ROOT, out) || out;
  if (check) {
    const have = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (have !== text) {
      console.error(`${rel} is stale. Regenerate with: bun run kit:bundle`);
      return 2;
    }
    console.log(`${rel} is up to date`);
    return 0;
  }
  writeFileSync(out, text);
  console.log(`wrote ${rel}`);
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
